#!/usr/bin/env node
// check-sri-integrity.js
//
// Fails if any <script src="..." integrity="sha384-..."> tag in
// web/index.html declares a hash that doesn't match the real, current
// SHA-384 of the file it references.
//
// Why this exists (see docs/audit or GitHub issue #119 for the full
// incident writeup): web/index.html's SRI hashes were hand-maintained
// and were last correct as of commit 43f50b1. Nine commits later
// (through 6c792e9..22ad998, the containerHealth feature branch and its
// revert), web/addon.js and web/data-providers.js were both edited
// repeatedly, but web/index.html's declared integrity hashes were never
// regenerated. Because Subresource Integrity failures are enforced
// silently by the browser (no application-level JS error, no visible
// console warning to a typical operator -- the script simply never
// executes), this left the addon completely non-functional (no tab
// click handlers ever attached, no data providers ever loaded) for at
// least 9 commits, undetected by the existing test suite, an L2+L3
// eight-hat audit, and a real operator report before being found.
//
// This check is a mechanical, deterministic comparison -- zero
// false-positive risk -- and must run as part of `npm test` so a
// future edit to web/addon.js or web/data-providers.js without a
// corresponding SRI regeneration (via scripts/update-sri.js) fails the
// build immediately instead of shipping broken.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const DEFAULT_REPO_ROOT = path.resolve(__dirname, '..');
const WEB_DIR_NAME = 'web';

// Matches <script src="foo.js?v=12345" integrity="sha384-XXXX"></script>
// Captures the referenced filename (without query string) and the
// declared base64 hash (without the "sha384-" prefix). Deliberately
// scoped to sha384 only -- every script tag in this file uses sha384
// today (see docs on why: 384 bits, W3C-recommended minimum for SRI).
const SCRIPT_TAG_RE =
  /<script\s+src="([^"?]+)(?:\?[^"]*)?"\s+integrity="sha384-([^"]+)"/g;

function computeSha384Base64(filePath) {
  const buf = fs.readFileSync(filePath); // nosemgrep
  return crypto.createHash('sha384').update(buf).digest('base64');
}

function extractDeclaredScriptHashes(repoRoot = DEFAULT_REPO_ROOT) {
  // repoRoot is never attacker/user-controlled: it defaults to this
  // script's own on-disk location (path.resolve(__dirname, '..')) and
  // is only ever overridden in test/governance.test.js with paths
  // generated by fs.mkdtempSync -- never from CLI args, env vars, or
  // network input. Not a real path-traversal sink.
  const htmlPath = path.join(repoRoot, WEB_DIR_NAME, 'index.html'); // nosemgrep: javascript.lang.security.audit.path-traversal.path-join-resolve-traversal.path-join-resolve-traversal
  const html = fs.readFileSync(htmlPath, 'utf8'); // nosemgrep

  const declared = [];
  let m;
  while ((m = SCRIPT_TAG_RE.exec(html)) !== null) {
    declared.push({ file: m[1], declaredHash: m[2] });
  }
  return declared;
}

function checkSriIntegrity(repoRoot = DEFAULT_REPO_ROOT) {
  const declared = extractDeclaredScriptHashes(repoRoot);

  if (declared.length === 0) {
    throw new Error(
      'web/index.html has no <script src="..." integrity="sha384-..."> tags -- has the SRI markup been removed or renamed?'
    );
  }

  const mismatches = [];
  for (const { file, declaredHash } of declared) {
    // `file` comes from parsing this repo's own committed, PR-reviewed
    // web/index.html (via SCRIPT_TAG_RE above), never from CLI args, env
    // vars, or network/user input -- same non-attacker-controlled
    // reasoning as repoRoot itself (see extractDeclaredScriptHashes).
    const filePath = path.join(repoRoot, WEB_DIR_NAME, file); // nosemgrep: javascript.lang.security.audit.path-traversal.path-join-resolve-traversal.path-join-resolve-traversal
    if (!fs.existsSync(filePath)) {
      mismatches.push({
        file,
        declaredHash,
        actualHash: null,
        reason: `referenced file does not exist at web/${file}`,
      });
      continue;
    }
    const actualHash = computeSha384Base64(filePath);
    if (actualHash !== declaredHash) {
      mismatches.push({ file, declaredHash, actualHash, reason: null });
    }
  }

  return { declaredCount: declared.length, mismatches };
}

function main() {
  const { declaredCount, mismatches } = checkSriIntegrity();

  if (mismatches.length === 0) {
    console.log(
      `SRI integrity check passed: ${declaredCount} script tag(s) in web/index.html all match the real, current SHA-384 of their referenced files.`
    );
    return 0;
  }

  console.error('FAIL: web/index.html has stale/incorrect SRI hashes.');
  console.error(
    '\nA mismatch here means browsers will silently refuse to execute the affected script(s) -- ' +
      'no visible error, the addon just stops responding. Run `node scripts/update-sri.js` to fix.\n'
  );
  for (const { file, declaredHash, actualHash, reason } of mismatches) {
    if (reason) {
      console.error(`  - ${file}: ${reason}`);
      continue;
    }
    console.error(`  - ${file}:`);
    console.error(`      declared: sha384-${declaredHash}`);
    console.error(`      actual:   sha384-${actualHash}`);
  }
  return 1;
}

if (require.main === module) {
  process.exit(main());
}

module.exports = {
  checkSriIntegrity,
  extractDeclaredScriptHashes,
  computeSha384Base64,
  SCRIPT_TAG_RE,
};
