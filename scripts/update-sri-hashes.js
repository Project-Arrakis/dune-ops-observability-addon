#!/usr/bin/env node
// update-sri-hashes.js — regenerates web/index.html's <script> integrity=
// (Subresource Integrity) attributes from the real, current on-disk
// content of every locally-referenced script.
//
// Why this exists (issue #119): SRI hashes were hand-maintained and
// drifted from the actual file content across 9 commits
// (6c792e9..22ad998), silently breaking the addon for every operator --
// a browser's SRI check refuses to execute a script whose hash doesn't
// match, with no visible error. Hand-maintenance was the direct cause;
// this script removes the manual step.
//
// Only touches <script src="local-file.js?v=..."> tags -- never a
// data-src (Grafana's lazy-loaded external iframes, see scripts/
// validate.js's matching, deliberately narrow <script ...src=> regex
// fixed for the same underlying reason in issue #122) and never a
// remote http(s):// src, which would need a different hashing story
// entirely (issue #122's exact confusion, avoided here on purpose).

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const DEFAULT_REPO_ROOT = path.resolve(__dirname, '..');
const DEFAULT_INDEX_HTML = 'web/index.html';

function sha384Base64(filePath) {
  const content = fs.readFileSync(filePath); // nosemgrep -- see path note below
  const hash = crypto.createHash('sha384').update(content).digest('base64');
  return `sha384-${hash}`;
}

// indexHtmlPath is never attacker/user-controlled: it defaults to this
// script's own on-disk location and is only ever overridden in
// test/governance.test.js with paths generated by fs.mkdtempSync --
// matching the same pattern and rationale already established in
// check-version-consistency.js. Not a real path-traversal sink.
function updateSriHashes(indexHtmlPath = path.join(DEFAULT_REPO_ROOT, DEFAULT_INDEX_HTML)) {
  const html = fs.readFileSync(indexHtmlPath, 'utf8'); // nosemgrep
  const dir = path.dirname(indexHtmlPath);
  const updates = [];

  // Scoped identically to validate.js's fixed regex (issue #122) --
  // only real <script ... src="local-file"> tags, never data-src or a
  // remote http(s):// URL (which this function cannot hash locally and
  // must not attempt to).
  const scriptTagPattern = /<script\b[^>]*\bsrc="([^"]+)"[^>]*>/g;
  const newHtml = html.replace(scriptTagPattern, (fullTag, src) => {
    if (/^https?:\/\//i.test(src)) {
      return fullTag; // remote script -- not this function's concern
    }
    const srcPath = src.split('?')[0];
    const fullPath = path.join(dir, srcPath);
    if (!fs.existsSync(fullPath)) {
      // Let validate.js's own missing-file check be the one that fails
      // loudly for this case -- this function's job is hashing, not
      // existence-checking, and silently skipping keeps the two
      // concerns cleanly separated.
      return fullTag;
    }
    const newHash = sha384Base64(fullPath);
    const integrityPattern = /integrity="sha384-[^"]*"/;
    let updatedTag;
    if (integrityPattern.test(fullTag)) {
      updatedTag = fullTag.replace(integrityPattern, `integrity="${newHash}"`);
    } else {
      // No existing integrity attribute -- add one, matching this
      // repo's own established convention of every local script
      // carrying SRI (never silently ship a script with no integrity
      // attribute at all just because it didn't have one before).
      updatedTag = fullTag.replace(/>$/, ` integrity="${newHash}">`);
    }
    if (updatedTag !== fullTag) {
      updates.push({ src, hash: newHash });
    }
    return updatedTag;
  });

  if (newHtml !== html) {
    fs.writeFileSync(indexHtmlPath, newHtml); // nosemgrep
  }

  return updates;
}

function main() {
  const updates = updateSriHashes();
  if (updates.length === 0) {
    console.log('SRI hashes already up to date -- no changes made.');
    return 0;
  }
  console.log(`Updated ${updates.length} SRI hash(es):`);
  for (const u of updates) {
    console.log(`  ${u.src} -> ${u.hash}`);
  }
  return 0;
}

if (require.main === module) {
  process.exit(main());
}

module.exports = { updateSriHashes, sha384Base64 };
